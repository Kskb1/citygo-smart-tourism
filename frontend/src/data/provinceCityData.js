export const provinceNames = Object.keys(provinceCityData)

export function findCityProfile(cityName) {
  const keyword = String(cityName || '').trim()
  if (!keyword) return null
  for (const [provinceName, provinceInfo] of Object.entries(provinceCityData)) {
    const cityInfo = provinceInfo.cities.find(item => item.name === keyword || item.name.includes(keyword) || keyword.includes(item.name))
    if (cityInfo) {
      return { provinceName, cityInfo }
    }
  }
  return null
}
